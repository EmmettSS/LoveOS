"""
constellations.py — هندسه‌ی «شکل‌های آسمان»

صورت‌های فلکیِ LoveOS دو دسته‌اند:
  • ``letter`` — حرف‌های اسم دخترم (M, A, R, Y …) که از پنل بابا می‌آیند
  • ``shape``  — شکل‌های آسمان (♥ قلب و ∞ بی‌نهایت) که هندسه‌شان ریاضی است

چرا این‌جا و نه در مدل؟
  چون این دو شکل «داده» نیستند، «ریاضی»‌اند. اگر در مدل یا seed هاردکد
  می‌شدند، هر تغییرِ ظریف (مثلاً تعداد ستاره‌ها) نیاز به مایگریشن داشت.
  این‌جا یک تابع خالص است: هم seed از آن می‌خواند، هم هر جای دیگری که بعداً
  لازم شود.

قراردادِ مختصات (مهم — با Starmap.tsx هماهنگ است):
  هر نقطه ``[x, y]`` در بازه‌ی ۰ تا ۱ است و **y رو به بالا** (مختصات ریاضی).
  بومِ SVG مبدأش گوشه‌ی بالا-چپ است، پس فرانت با ``toCanvasY(y) = 1 - y``
  آن را برمی‌گرداند. بدون این قرارداد، قلب واژگون و نوکش رو به بالا دیده
  می‌شود — همان باگی که قبلاً حرف «M» را شبیه «W» می‌کرد.

  نقطه‌ی نخست و آخر هر دو شکل **یکی** است تا پلی‌لاین بسته شود؛ وگرنه در
  فرورفتگیِ بالای قلب (و در سمت راستِ بی‌نهایت) یک شکافِ دیده‌شدنی می‌ماند.
"""
from __future__ import annotations

import math

# ---------------------------------------------------------------- قلب ♥ ---
def heart_stars(n: int = 16) -> list[list[float]]:
    """
    منحنیِ کلاسیکِ قلب:
        x = 16·sin³(t)
        y = 13·cos(t) − 5·cos(2t) − 2·cos(3t) − cos(4t)

    ``n`` بازه‌ی دایره را نمونه می‌گیرد و ``n + 1`` نقطه برمی‌گرداند تا حلقه
    بسته شود. با n=16 قلب هم به‌اندازه‌ی کافی گرد است و هم ستاره‌هایش از هم
    قابلِ تشخیص‌اند (۱۷ ستاره).
    """
    raw: list[tuple[float, float]] = []
    for i in range(n + 1):
        t = 2 * math.pi * i / n
        raw.append(
            (
                16 * math.sin(t) ** 3,
                13 * math.cos(t) - 5 * math.cos(2 * t) - 2 * math.cos(3 * t) - math.cos(4 * t),
            )
        )
    return _normalize(raw)


# ------------------------------------------------------- بی‌نهایت ∞ ---
def infinity_stars(n: int = 20) -> list[list[float]]:
    """
    لمینیسکاتِ برنولی (همان شکلِ علامت ∞):
        x = cos(t) / (1 + sin²(t))
        y = sin(t)·cos(t) / (1 + sin²(t))

    یک دورِ کامل t از ۰ تا ۲π، کلِ هشت را **دقیقاً یک بار** می‌پیماید و از
    مرکز (۰٫۵، ۰٫۵) دو بار عبور می‌کند — همان گره‌ی وسطِ ∞.
    """
    raw: list[tuple[float, float]] = []
    for i in range(n + 1):
        t = 2 * math.pi * i / n
        d = 1 + math.sin(t) ** 2
        raw.append((math.cos(t) / d, math.sin(t) * math.cos(t) / d))
    return _normalize(raw)


def _normalize(raw: list[tuple[float, float]], ndigits: int = 3) -> list[list[float]]:
    """مختصات را به جعبه‌ی ۰..۱ می‌بَرد؛ گردکردن تا JSON کوچک بماند."""
    xs = [p[0] for p in raw]
    ys = [p[1] for p in raw]
    min_x, max_x, min_y, max_y = min(xs), max(xs), min(ys), max(ys)
    span_x = (max_x - min_x) or 1.0
    span_y = (max_y - min_y) or 1.0
    return [[round((x - min_x) / span_x, ndigits), round((y - min_y) / span_y, ndigits)] for x, y in raw]


